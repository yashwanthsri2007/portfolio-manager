import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { PortfolioMetrics, Holding, UserProfile } from '../types';
import { formatCurrency, formatPercent } from '../utils/formatters';

export function generatePDFReport(metrics: PortfolioMetrics, holdings: Holding[], user: UserProfile) {
  const doc = new jsPDF();
  const dateStr = new Date().toISOString().split('T')[0];
  const yearMonth = dateStr.substring(0, 7).replace('-', '_');

  // Header Banner
  doc.setFillColor(11, 15, 23); // #0B0F17
  doc.rect(0, 0, 210, 40, 'F');

  doc.setTextColor(6, 182, 212); // #06B6D4 Cyan
  doc.setFontSize(22);
  doc.setFont('helvetica', 'bold');
  doc.text('PORTFOLIO MANAGER', 14, 20);

  doc.setFontSize(10);
  doc.setTextColor(156, 163, 175);
  doc.text('Investment & Cash Management Ledger Report', 14, 28);
  doc.text(`Generated: ${dateStr}`, 150, 20);
  doc.text(`Account: ${user.name}`, 150, 28);

  // Executive Summary Card
  doc.setFillColor(243, 244, 246);
  doc.rect(14, 45, 182, 35, 'F');
  doc.setDrawColor(6, 182, 212);
  doc.rect(14, 45, 182, 35, 'D');

  doc.setTextColor(31, 41, 55);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.text('TOTAL NET WORTH', 20, 54);

  doc.setFontSize(18);
  doc.setTextColor(6, 182, 212);
  doc.text(formatCurrency(metrics.totalNetWorth), 20, 64);

  doc.setFontSize(10);
  doc.setTextColor(55, 65, 81);
  doc.text(`Available Cash: ${formatCurrency(metrics.availableCash)}`, 110, 52);
  doc.text(`Invested Capital: ${formatCurrency(metrics.totalInvested)}`, 110, 60);
  doc.text(`Total P&L: ${formatCurrency(metrics.totalProfitLoss)} (${formatPercent(metrics.totalReturnPercent)})`, 110, 68);

  // Asset Allocation Table
  doc.setFontSize(12);
  doc.setTextColor(11, 15, 23);
  doc.setFont('helvetica', 'bold');
  doc.text('1. ASSET ALLOCATION BREAKDOWN', 14, 90);

  const allocationRows = metrics.assetAllocation.map(a => [
    a.category,
    formatCurrency(a.amount),
    `${a.percentage.toFixed(2)}%`,
    formatCurrency(a.profitLoss),
    formatPercent(a.returnPercent)
  ]);

  autoTable(doc, {
    startY: 95,
    head: [['Asset Class', 'Current Value', 'Allocation %', 'Profit / Loss', 'Return %']],
    body: allocationRows,
    headStyles: { fillColor: [11, 15, 23], textColor: [6, 182, 212], fontStyle: 'bold' },
    alternateRowStyles: { fillColor: [249, 250, 251] },
    theme: 'grid'
  });

  // Holdings Summary Table
  const finalY = (doc as any).lastAutoTable.finalY || 140;
  doc.setFontSize(12);
  doc.setTextColor(11, 15, 23);
  doc.setFont('helvetica', 'bold');
  doc.text('2. TOP PORTFOLIO HOLDINGS', 14, finalY + 15);

  const holdingsRows = holdings.slice(0, 10).map(h => [
    h.symbol,
    h.name,
    h.assetType.toUpperCase().replace('_', ' '),
    h.quantity.toString(),
    formatCurrency(h.averagePrice),
    h.broker || 'Direct'
  ]);

  autoTable(doc, {
    startY: finalY + 20,
    head: [['Symbol', 'Asset Name', 'Type', 'Quantity', 'Avg Price', 'Broker']],
    body: holdingsRows,
    headStyles: { fillColor: [17, 24, 39], textColor: [255, 255, 255] },
    theme: 'striped'
  });

  // Risk & Health Assessment
  const page2Y = (doc as any).lastAutoTable.finalY || 200;
  doc.setFontSize(12);
  doc.setTextColor(11, 15, 23);
  doc.setFont('helvetica', 'bold');
  doc.text('3. HEALTH & RISK DIAGNOSTIC SUMMARY', 14, page2Y + 15);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(55, 65, 81);
  doc.text(`• Diversification Health Score: ${metrics.diversificationScore}/100`, 20, page2Y + 25);
  doc.text(`• Portfolio Sentiment Score: ${metrics.portfolioSentimentScore}/100`, 20, page2Y + 32);
  doc.text(`• Top Gainer Asset: ${metrics.topGainer ? `${metrics.topGainer.name} (${formatPercent(metrics.topGainer.changePercent)})` : 'N/A'}`, 20, page2Y + 39);
  doc.text(`• Top Concentration: ${metrics.concentrationRisk[0] ? `${metrics.concentrationRisk[0].name} (${metrics.concentrationRisk[0].weight.toFixed(1)}%)` : 'Balanced'}`, 20, page2Y + 46);

  // Footer Disclaimer
  doc.setFontSize(8);
  doc.setTextColor(156, 163, 175);
  doc.text('Confidential — Generated by Portfolio Manager. Informational investment tracking purposes only.', 14, 285);

  // Download PDF
  doc.save(`PORTFOLIO_MANAGER_REPORT_${yearMonth}.pdf`);
}
